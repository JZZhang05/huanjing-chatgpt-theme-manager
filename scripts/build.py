"""Build the public Windows x64 installer without private settings or Workshop media."""
from pathlib import Path
import argparse
import json
import os
import shutil
import subprocess
import zipfile
from prepare_runtime import prepare,digest

ROOT=Path(__file__).resolve().parents[1]
BUILD=ROOT/'build'
PAYLOAD=BUILD/'payload'
DIST=ROOT/'dist'

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--offline',action='store_true',help='Require dependencies already verified in .cache')
    args=parser.parse_args()
    config=json.loads((ROOT/'config.json').read_text(encoding='utf8'))
    version=config['version']
    if os.name!='nt': raise RuntimeError('Installer builds require Windows x64 and .NET Framework 4.8')
    # This directory is always generated by this build; never point cleanup at an installation.
    if BUILD.exists():
        assert BUILD.resolve().parent==ROOT.resolve() and BUILD.name=='build'
        shutil.rmtree(BUILD)
    PAYLOAD.mkdir(parents=True)
    DIST.mkdir(exist_ok=True)
    for file in (ROOT/'src').iterdir():
        if not file.is_file(): continue
        content=file.read_text(encoding='utf-8-sig')
        if file.suffix in {'.cs','.ps1'}: content=content.replace('1.1.0',version)
        (PAYLOAD/file.name).write_text(content,encoding='utf-8-sig' if file.suffix=='.ps1' else 'utf8')
    shutil.copytree(ROOT/'defaults',PAYLOAD/'defaults')
    shutil.copytree(ROOT/'assets',PAYLOAD,dirs_exist_ok=True)
    (PAYLOAD/'media').mkdir()
    shutil.copy2(ROOT/'docs/usage.md',PAYLOAD/'使用说明.md')
    (PAYLOAD/'使用说明.txt').write_text((ROOT/'docs/usage.md').read_text(encoding='utf8'),encoding='utf-8-sig')
    shutil.copy2(ROOT/'docs/wallpapers.md',PAYLOAD/'壁纸来源.txt')
    shutil.copy2(ROOT/'LICENSE',PAYLOAD/'LICENSE.txt')
    shutil.copy2(ROOT/'THIRD-PARTY-NOTICES.txt',PAYLOAD/'THIRD-PARTY-NOTICES.txt')
    (PAYLOAD/'tools').mkdir()
    shutil.copy2(ROOT/'scripts/ffmpeg-download.json',PAYLOAD/'tools/ffmpeg-download.json')
    prepare(PAYLOAD,offline=args.offline)
    csc=Path(os.environ['WINDIR'])/'Microsoft.NET/Framework64/v4.0.30319/csc.exe'
    def compile_cs(source,output,extra=()):
        subprocess.run([str(csc),'/nologo','/target:winexe','/platform:x64','/optimize+','/debug-',
            '/reference:System.Management.dll','/reference:System.Web.Extensions.dll',
            '/reference:System.Windows.Forms.dll','/win32icon:'+str(PAYLOAD/'theme.ico'),
            '/win32manifest:'+str(ROOT/'installer/app.manifest'),
            '/out:'+str(output),*extra,str(source)],check=True)
    compile_cs(PAYLOAD/'LaunchChatGPT.cs',PAYLOAD/'LaunchChatGPT.exe')
    # Ship all custom source needed to inspect and rebuild the installer.
    source=PAYLOAD/'source'
    source.mkdir()
    for directory in ['src','assets','defaults','installer','scripts','tests','docs','.github']:
        if not (ROOT/directory).is_dir(): continue
        shutil.copytree(ROOT/directory,source/directory,ignore=shutil.ignore_patterns('__pycache__','*.pyc'))
    for name in ['config.json','package.json','LICENSE','README.md','THIRD-PARTY-NOTICES.txt',
                 'SECURITY.md','PRIVACY.md','CHANGELOG.md','CONTRIBUTING.md','.gitignore','.gitattributes']:
        if not (ROOT/name).is_file(): continue
        shutil.copy2(ROOT/name,source/name)
    files=[]
    for file in sorted(PAYLOAD.rglob('*')):
        if not file.is_file(): continue
        relative=file.relative_to(PAYLOAD).as_posix()
        if file.suffix in {'.pyc','.mp4'} or '__pycache__' in file.parts:
            raise RuntimeError('Unexpected generated data or unlicensed media: '+relative)
        if file.suffix.lower() in {'.json','.txt','.md','.ps1','.cs','.mjs','.js','.css','.vbs','.cmd','.py'}:
            data=file.read_bytes().lower()
            home=str(Path.home()).lower()
            if any(value.encode() in data for value in [home,home.replace('\\','\\\\'),home.replace('\\','/')]):
                raise RuntimeError('Private build-machine path: '+relative)
        files.append({'path':relative,'bytes':file.stat().st_size,'sha256':digest(file)})
    manifest={**config,'client':'Official ChatGPT for Windows, OpenAI.Codex_2p2nqsd0c76g0',
              'architecture':'x64','wallpapers':1,'edition':'public','files':files}
    (PAYLOAD/'package-manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf8')
    archive=BUILD/'payload.zip'
    with zipfile.ZipFile(archive,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=6) as output:
        for file in sorted(PAYLOAD.rglob('*')):
            if file.is_file(): output.write(file,file.relative_to(PAYLOAD).as_posix())
    setup=BUILD/'Setup.cs'
    setup.write_text((ROOT/'installer/Setup.cs').read_text(encoding='utf8').replace('1.1.0',version),encoding='utf8')
    installer=DIST/('Huanjing-Setup-'+version+'.exe')
    compile_cs(setup,installer,[
        '/reference:System.Drawing.dll','/reference:System.IO.Compression.dll',
        '/reference:System.IO.Compression.FileSystem.dll','/reference:Microsoft.CSharp.dll',
        '/resource:'+str(archive)+',payload.zip'])
    for name in ['LICENSE.txt','使用说明.md','壁纸来源.txt','THIRD-PARTY-NOTICES.txt']:
        shutil.copy2(PAYLOAD/name,DIST/name)
    names=[installer.name,'LICENSE.txt','使用说明.md','壁纸来源.txt','THIRD-PARTY-NOTICES.txt']
    (DIST/'SHA256SUMS.txt').write_text(''.join(digest(DIST/name)+'  '+name+'\n' for name in names),encoding='utf8')
    print(json.dumps({'version':version,'files':len(files),'installer':installer.name,
        'MiB':round(installer.stat().st_size/1024**2,1),'sha256':digest(installer)}))

if __name__=='__main__': main()
